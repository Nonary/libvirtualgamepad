inline constexpr std::size_t report_descriptor_size = sizeof(report_descriptor);
inline constexpr std::uint8_t calibration_id = 0x05;
inline constexpr std::uint8_t control_id = 0x08;
inline constexpr std::uint8_t pairing_id = 0x09;
inline constexpr std::uint8_t firmware_id = 0x20;

// Zero biases; +/-8192 raw gyro counts at +/-512 degrees/s yields 16
// counts/(degree/s), matching our encoder. Acceleration is 8192 counts/g.
inline constexpr std::array<std::uint8_t, 41> calibration = {
  5, 0, 0, 0, 0, 0, 0,
  0, 0x20, 0, 0xe0, 0, 0x20, 0, 0xe0, 0, 0x20, 0, 0xe0,
  0, 2, 0, 2,
  0, 0x20, 0, 0xe0, 0, 0x20, 0, 0xe0, 0, 0x20, 0, 0xe0,
  0, 0, 0, 0, 0, 0
};

// Native hosts select calibration usage 33 for the USB protocol introduced at
// firmware 0x0001003e. An older revision selects usage 23 instead. This is a
// protocol compatibility revision, not our package version or a factory build.
//
// Offset 44 is the 16-bit UpdateVersion libScePad reads. 007 First Light's
// libScePad.dll returns SCE_PAD_UPDATE_REQUIRED when this is below 0x0390
// and skips adaptive triggers and vibration.
inline constexpr std::uint16_t update_version = 0x0390;
inline constexpr std::array<std::uint8_t, 64> firmware = [] {
  std::array<std::uint8_t, 64> value {};
  value[0] = firmware_id;
  value[25] = 1; // Hardware version, retained from our original profile.
  value[28] = 0x3e;
  value[30] = 1;
  value[44] = static_cast<std::uint8_t>(update_version);
  value[45] = static_cast<std::uint8_t>(update_version >> 8);
  return value;
}();
struct feature_state {
  // Least-significant wire octet first, unique per controller slot. The final
  // octet has the locally administered bit and no multicast bit.
  std::array<std::uint8_t, 6> address {0, 0x53, 0x50, 0x47, 0x56, 0x02};
  bool sensors_enabled = true;
};
inline std::size_t get_feature(std::uint8_t id, std::uint8_t *buffer,
                               std::size_t capacity, const feature_state &state) noexcept {
  std::size_t length = 0;
  switch (id) {
    case calibration_id: length = calibration.size(); break;
    case pairing_id: length = 20; break;
    case firmware_id: length = firmware.size(); break;
    default: return 0;
  }
  if (buffer == nullptr || capacity < length) return 0;
  std::memset(buffer, 0, capacity);
  switch (id) {
    case calibration_id: std::memcpy(buffer, calibration.data(), length); break;
    case firmware_id: std::memcpy(buffer, firmware.data(), length); break;
    case pairing_id:
      buffer[0] = id;
      std::memcpy(buffer + 1, state.address.data(), state.address.size());
      break;
  }
  return length;
}
inline bool set_feature(std::uint8_t id, const std::uint8_t *buffer,
                        std::size_t size, feature_state &state) noexcept {
  if (id != control_id || buffer == nullptr || size < 48 ||
      buffer[0] != control_id || buffer[1] != 2) return false;
  // Native USB sensor-enable command. Unknown commands and nonzero reserved
  // payload are unsupported. HID may pad the 48-byte report to its maximum.
  for (std::size_t i = 2; i < 48; ++i) if (buffer[i] != 0) return false;
  state.sensors_enabled = true; // Sensors already stream in our USB report 1.
  return true;
}
